-- Deterministic pseudo-random numbers for the generators: gen.Rand(key) returns R1..R16, floats in [0, 1).
IF OBJECT_ID(N'gen.Rand') IS NOT NULL DROP FUNCTION gen.Rand;
IF SCHEMA_ID(N'gen') IS NULL EXEC (N'CREATE SCHEMA gen AUTHORIZATION dbo');
GO
CREATE FUNCTION gen.Rand (@key bigint)
RETURNS TABLE
WITH SCHEMABINDING
AS
RETURN
SELECT (CAST(CAST(SUBSTRING(h.A, 1, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R1,
       (CAST(CAST(SUBSTRING(h.A, 5, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R2,
       (CAST(CAST(SUBSTRING(h.A, 9, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R3,
       (CAST(CAST(SUBSTRING(h.A, 13, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R4,
       (CAST(CAST(SUBSTRING(h.A, 17, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R5,
       (CAST(CAST(SUBSTRING(h.A, 21, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R6,
       (CAST(CAST(SUBSTRING(h.A, 25, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R7,
       (CAST(CAST(SUBSTRING(h.A, 29, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R8,
       (CAST(CAST(SUBSTRING(h.B, 1, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R9,
       (CAST(CAST(SUBSTRING(h.B, 5, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R10,
       (CAST(CAST(SUBSTRING(h.B, 9, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R11,
       (CAST(CAST(SUBSTRING(h.B, 13, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R12,
       (CAST(CAST(SUBSTRING(h.B, 17, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R13,
       (CAST(CAST(SUBSTRING(h.B, 21, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R14,
       (CAST(CAST(SUBSTRING(h.B, 25, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R15,
       (CAST(CAST(SUBSTRING(h.B, 29, 4) AS int) AS bigint) + 2147483648) / 4294967296.0 AS R16
FROM (SELECT HASHBYTES('SHA2_256', CONCAT(@key, ':a')) AS A, HASHBYTES('SHA2_256', CONCAT(@key, ':b')) AS B) h;
GO

