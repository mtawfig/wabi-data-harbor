import random

HEADER_RULE = "-- " + "=" * 110


def q(value):
    """SQL literal for a Python value (N'' for text, NULL for None)."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(round(value, 4)) if isinstance(value, float) else str(value)
    return "N'" + str(value).replace("'", "''") + "'"


def insert(table, columns, rows, chunk=500):
    """INSERT ... VALUES split into chunks (SQL Server allows 1000 rows per VALUES list)."""
    out = []
    for i in range(0, len(rows), chunk):
        part = rows[i:i + chunk]
        out.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES")
        out.append(",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in part) + ";")
    return "\n".join(out)


